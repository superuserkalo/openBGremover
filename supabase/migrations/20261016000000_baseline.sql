-- Baseline of the production Supabase schema (project openBGremover), captured
-- read-only from the catalog on 16 October 2026. Production has no recorded
-- migrations; this file records what already exists so self-hosted and new
-- environments can be created from the repository.
--
-- Production already contains these objects. Before applying migrations there
-- with the Supabase CLI, mark this one applied instead of running it:
--   supabase migration repair --status applied 20261016000000
--
-- Not captured here: rows (including the internal trial service key, an
-- api_keys row with is_service = true), auth configuration, and signing keys.

CREATE TYPE public.billing_model_enum AS ENUM ('free_tier', 'pay_as_you_go', 'bulk');

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  current_billing_model public.billing_model_enum NOT NULL DEFAULT 'free_tier',
  free_images_remaining bigint NOT NULL DEFAULT 50,
  free_images_reset_at timestamptz NOT NULL DEFAULT (now() + interval '1 mon'),
  bulk_images_remaining bigint NOT NULL DEFAULT 0,
  payg_usage_this_period bigint NOT NULL DEFAULT 0,
  stripe_customer_id text,
  stripe_subscription_id text UNIQUE,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);
COMMENT ON TABLE public.profiles IS 'for billing and subscription types';
CREATE UNIQUE INDEX profiles_stripe_customer_id_key ON public.profiles (stripe_customer_id)
  WHERE stripe_customer_id IS NOT NULL AND stripe_customer_id <> '';

CREATE TABLE public.api_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES public.profiles (id) ON DELETE CASCADE,
  key_name text NOT NULL,
  hashed_key text NOT NULL,
  created_at timestamp DEFAULT now(),
  last_used_at timestamptz DEFAULT now(),
  is_active boolean NOT NULL DEFAULT true,
  key_prefix text,
  updated_at timestamp DEFAULT now(),
  is_service boolean NOT NULL DEFAULT false,
  scopes text[] NOT NULL DEFAULT '{}'
);
COMMENT ON TABLE public.api_keys IS 'user generated api keys';
CREATE INDEX api_keys_is_service_idx ON public.api_keys (is_service);
CREATE INDEX api_keys_scopes_gin ON public.api_keys USING gin (scopes);

CREATE TABLE public.usage_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  api_key_id bigint REFERENCES public.api_keys (id) ON DELETE SET NULL,
  source text NOT NULL,
  was_successful boolean NOT NULL,
  error_message text,
  processing_time_ms integer,
  credit_type_used text,
  created_at timestamptz DEFAULT now()
);
CREATE INDEX idx_logs_api_key_id ON public.usage_logs (api_key_id);
CREATE INDEX idx_logs_user_id_created_at ON public.usage_logs (user_id, created_at DESC);
CREATE INDEX idx_logs_was_successful ON public.usage_logs (was_successful);

CREATE TABLE public.trial_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id text NOT NULL,
  ip_hash text NOT NULL,
  issued_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz
);
CREATE INDEX idx_trial_tokens_consumed ON public.trial_tokens (consumed_at);
CREATE INDEX idx_trial_tokens_device_recent ON public.trial_tokens (device_id, issued_at DESC);
CREATE INDEX idx_trial_tokens_ip_recent ON public.trial_tokens (ip_hash, issued_at DESC);

-- RLS is enabled on every table. Only profile insertion has a policy, so other
-- access depends on a role that bypasses RLS.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.api_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usage_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trial_tokens ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Insert profile on signup" ON public.profiles
  AS PERMISSIVE FOR INSERT TO public
  WITH CHECK (
    auth.uid() = id
    OR CURRENT_USER = ANY (ARRAY['supabase_auth_admin'::name, 'postgres'::name, 'supabase_admin'::name])
    OR auth.role() = 'service_role'
  );

CREATE FUNCTION public.handle_new_user()
  RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'public'
AS $function$
BEGIN
  INSERT INTO public.profiles (id)
  VALUES (new.id);
  RETURN new;
END;
$function$;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
